static int b64_val(char c) {
  if (c >= 'A' && c <= 'Z')
    return c - 'A';
  if (c >= 'a' && c <= 'z')
    return c - 'a' + 26;
  if (c >= '0' && c <= '9')
    return c - '0' + 52;
  if (c == '+')
    return 62;
  if (c == '/')
    return 63;
  return -1;
}

/* Fixed-size base64 decode for the key only (no padding edge cases beyond =). */
static int decode_key(uint8_t *out, size_t out_cap, size_t *out_len) {
  const char *in = kObfKeyB64;
  size_t in_len = sizeof(kObfKeyB64) - 1;
  size_t o = 0;
  size_t i = 0;

  while (i + 3 < in_len) {
    char c0 = in[i], c1 = in[i + 1], c2 = in[i + 2], c3 = in[i + 3];
    if (c0 == '=' || c1 == '=')
      break;
    int v0 = b64_val(c0);
    int v1 = b64_val(c1);
    int v2 = c2 == '=' ? 0 : b64_val(c2);
    int v3 = c3 == '=' ? 0 : b64_val(c3);
    if (v0 < 0 || v1 < 0 || (c2 != '=' && v2 < 0) || (c3 != '=' && v3 < 0))
      return -1;
    if (o >= out_cap)
      return -1;
    out[o++] = (uint8_t)((v0 << 2) | (v1 >> 4));
    if (c2 != '=') {
      if (o >= out_cap)
        return -1;
      out[o++] = (uint8_t)(((v1 & 0xf) << 4) | (v2 >> 2));
    }
    if (c3 != '=') {
      if (o >= out_cap)
        return -1;
      out[o++] = (uint8_t)(((v2 & 0x3) << 6) | v3);
    }
    i += 4;
  }
  *out_len = o;
  return o > 0 ? 0 : -1;
}

int onion_obf_decode(const uint8_t *enc, size_t n, char *out, size_t out_sz) {
  uint8_t key[32];
  size_t key_len = 0;
  size_t i;

  if (!enc || !out || out_sz == 0 || n >= out_sz)
    return -1;
  if (decode_key(key, sizeof(key), &key_len) != 0 || key_len == 0)
    return -1;

  for (i = 0; i < n; ++i) {
    uint8_t b = enc[i];
    b = (uint8_t)(b - (uint8_t)(i * 17u + 31u));
    b ^= key[i % key_len];
    out[i] = (char)b;
  }
  out[n] = '\0';

  /* Wipe key material. */
  memset(key, 0, sizeof(key));
  return 0;
}

void onion_notify_debug_obf(const uint8_t *en, size_t en_n, const uint8_t *zh,
                            size_t zh_n) {
  char plain[384];
  const uint8_t *blob;
  size_t n;
  size_t i;

  if (!en || !zh || en_n == 0 || zh_n == 0)
    return;

  if (onion_notify_get_language() == ONION_NOTIFY_LANG_ZH_HANS) {
    blob = zh;
    n = zh_n;
  } else {
    blob = en;
    n = en_n;
  }

  if (onion_obf_decode(blob, n, plain, sizeof(plain)) != 0)
    return;

  /*
   * Pass as %s so the decoded body is not re-interpreted as a printf format,
   * and so onion_notify_tr("%s") is a no-op (no catalog entry).
   */
  onion_notify_debug("%s", plain);

  for (i = 0; i < sizeof(plain); ++i)
    plain[i] = '\0';
}

void onion_notify_debug_integrity_failed(void) {
  onion_notify_debug_obf(kIntegrityEn, sizeof(kIntegrityEn), kIntegrityZh,
                         sizeof(kIntegrityZh));
}

void onion_notify_debug_beta_redistrib(void) {
  onion_notify_debug_obf(kRedistribEn, sizeof(kRedistribEn), kRedistribZh,
                         sizeof(kRedistribZh));
}
